GRID = (0.0, 0.0, 1.0)    # pure blue grid lines
KEY = (1.0, 0.0, 1.0)     # magenta: transparent
COLS = 26
GLYPHS = 154


def glyph_order():
    """Glyph number -> character (None = left empty), as the engine's char map."""
    order = [None] * (GLYPHS + 1)
    for i in range(26):
        order[1 + i] = chr(ord("A") + i)
        order[27 + i] = chr(ord("a") + i)
    for i, d in enumerate("1234567890"):
        order[53 + i] = d
    for i, ch in enumerate(PUNCT_ORDER):
        order[63 + i] = ch
    return order


def sheet(scale, ink, shadow):
    """A grid sheet with every glyph drawn `scale` times (one dot = scale x scale px)."""
    # Box: 1 empty column + 5 dots + 1 shadow, 9 rows + 1 shadow; the pitch adds the line.
    box = max(1 + 5 * scale + scale, 9 * scale + scale) + 1
    pitch = box + 2
    rows = (GLYPHS + COLS - 1) // COLS
    w, h = COLS * pitch + 1, rows * pitch + 2
    c = Canvas(w, h, KEY)
    for y in range(rows * pitch + 1):
        for x in range(w):
            if x % pitch == 0 or y % pitch == 0:
                c.px[y][x] = list(GRID)
    for g, ch in enumerate(glyph_order()):
        if ch is None:
            continue
        cx, cy = ((g - 1) % COLS) * pitch + 1, ((g - 1) // COLS) * pitch + 1
        bitmap = G[ch]
        # Shadow first (down-right), then the ink over it.
        for colour, off in ((shadow, scale), (ink, 0)):
            for ry, row in enumerate(bitmap):
                for rx, dot in enumerate(row):
                    if dot == "#":
                        x0 = cx + scale + rx * scale + off  # column 0..scale-1 stays empty
                        y0 = cy + ry * scale + off
                        c.rect(x0, y0, x0 + scale, y0 + scale, colour)
    return c


def build_all():
    os.makedirs(OUT, exist_ok=True)
    cream, brown = (0.96, 0.91, 0.78), (0.16, 0.12, 0.06)
    gold = (0.95, 0.78, 0.36)
    written = []
    for name, scale, ink in (("body", 1, cream), ("title", 2, gold)):
        img = sheet(scale, ink, brown)
        img.save(os.path.join(OUT, f"font_{name}.png"))
        written.append((f"font_{name}.png", img.w, img.h))
    return written


if __name__ == "__main__":
    for name, w, h in build_all():
        print(f"{name:28s} {w}x{h}")

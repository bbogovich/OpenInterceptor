#!/usr/bin/env python3
"""Generates the original-free models and texture of the `sample` pack.

Everything in packs/sample is made here from scratch, so the sample pack (and the
engine's tests) never depend on X-COM: Interceptor data. Run from the repository root:

    python3 tools/make_sample_models.py

Conventions for mod models (see the docs site, Modding > Models): metres, +Y up, the
nose pointing along -Z, Wavefront OBJ with an .mtl material library.
"""
import math
import os
import struct
import zlib

OUT = os.path.join("packs", "sample")


class Obj:
    """Collects vertices and faces, then writes an OBJ + MTL pair."""

    def __init__(self, name):
        self.name, self.v, self.vt, self.faces = name, [], [], []

    def vert(self, x, y, z):
        self.v.append((x, y, z))
        return len(self.v)  # OBJ indices are 1-based

    def face(self, material, *idx, uv=None):
        self.faces.append((material, idx, uv))

    def write(self, materials):
        base = os.path.join(OUT, "models", self.name)
        with open(base + ".mtl", "w") as f:
            for m, (rgb, tex) in materials.items():
                f.write(f"newmtl {m}\nKd {rgb[0]} {rgb[1]} {rgb[2]}\n")
                if tex:
                    f.write(f"map_Kd {tex}\n")
        with open(base + ".obj", "w") as f:
            f.write(f"# {self.name}: generated by tools/make_sample_models.py\n")
            f.write(f"mtllib {self.name}.mtl\n")
            for x, y, z in self.v:
                f.write(f"v {x:.4f} {y:.4f} {z:.4f}\n")
            for u, v in self.vt:
                f.write(f"vt {u:.4f} {v:.4f}\n")
            current = None
            for m, idx, uv in self.faces:
                if m != current:
                    f.write(f"usemtl {m}\n")
                    current = m
                if uv:
                    f.write("f " + " ".join(f"{i}/{t}" for i, t in zip(idx, uv)) + "\n")
                else:
                    f.write("f " + " ".join(str(i) for i in idx) + "\n")


def dart():
    """A small arrow-head fighter, about 12 m long."""
    o = Obj("dart")
    nose = o.vert(0, 0, -7)
    top = o.vert(0, 1.4, 1)
    bottom = o.vert(0, -0.9, 1.5)
    left = o.vert(-5, -0.2, 3)
    right = o.vert(5, -0.2, 3)
    tail = o.vert(0, 0.2, 3.5)
    canopy = o.vert(0, 1.0, -2)
    o.face("hull", nose, left, top)
    o.face("hull", nose, top, right)
    o.face("hull", nose, bottom, left)
    o.face("hull", nose, right, bottom)
    o.face("engine", left, tail, top)
    o.face("engine", top, tail, right)
    o.face("engine", left, bottom, tail)
    o.face("engine", tail, bottom, right)
    o.face("canopy", nose, top, canopy)
    o.write({"hull": ((0.55, 0.62, 0.75), None), "engine": ((1.0, 0.55, 0.15), None), "canopy": ((0.3, 0.9, 1.0), None)})


def raider():
    """A red double-diamond raider, about 14 m long."""
    o = Obj("raider")
    n = o.vert(0, 0, -7)
    b = o.vert(0, 0, 7)
    ring = [o.vert(6 * math.cos(a), 1.5 * math.sin(a), 0) for a in [k * math.pi / 2 for k in range(4)]]
    for k in range(4):
        a, c = ring[k], ring[(k + 1) % 4]
        o.face("hull", n, c, a)
        o.face("dark", b, a, c)
    o.write({"hull": ((0.85, 0.15, 0.12), None), "dark": ((0.25, 0.08, 0.08), None)})


def ring_station():
    """A 600 m ring station with a hub and four spokes; the ring is textured."""
    o = Obj("ring")
    segs, R, w, h = 24, 300.0, 40.0, 30.0
    o.vt += [(0, 0), (4, 0), (4, 1), (0, 1)]
    rings = []
    for k in range(segs):
        a = 2 * math.pi * k / segs
        c, s = math.cos(a), math.sin(a)
        rings.append([o.vert((R - w / 2) * c, -h / 2, (R - w / 2) * s), o.vert((R + w / 2) * c, -h / 2, (R + w / 2) * s),
                      o.vert((R + w / 2) * c, h / 2, (R + w / 2) * s), o.vert((R - w / 2) * c, h / 2, (R - w / 2) * s)])
    for k in range(segs):
        p, q = rings[k], rings[(k + 1) % segs]
        for i in range(4):
            j = (i + 1) % 4
            o.face("panel", p[i], q[i], q[j], p[j], uv=(1, 2, 3, 4))
    # Hub: a box.
    hub = [o.vert(x, y, z) for x in (-40, 40) for y in (-40, 40) for z in (-40, 40)]
    for quad in [(0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1), (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3)]:
        o.face("hub", *[hub[i] for i in quad])
    # Spokes: thin boxes along +X, -X, +Z, -Z.
    for dx, dz in [(1, 0), (-1, 0), (0, 1), (0, -1)]:
        a, b = 40.0, R - w / 2
        if dx:
            pts = [o.vert(dx * a, y, z) for y in (-6, 6) for z in (-6, 6)] + [o.vert(dx * b, y, z) for y in (-6, 6) for z in (-6, 6)]
        else:
            pts = [o.vert(x, y, dz * a) for x in (-6, 6) for y in (-6, 6)] + [o.vert(x, y, dz * b) for x in (-6, 6) for y in (-6, 6)]
        for quad in [(0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]:
            o.face("hub", *[pts[i] for i in quad])
    o.write({"panel": ((1, 1, 1), "../textures/panel.png"), "hub": ((0.7, 0.7, 0.75), None)})


def panel_png():
    """A 64x64 hull-panel texture: grey plates with dark seams and a few lights."""
    w = h = 64
    rows = []
    for y in range(h):
        row = bytearray([0])
        for x in range(w):
            seam = x % 16 == 0 or y % 32 == 0
            light = (x % 16 == 8) and (y % 32 == 16)
            c = (40, 40, 48) if seam else (255, 220, 120) if light else (150 + (x * 7 + y * 3) % 20,) * 3
            row += bytes(c)
        rows.append(bytes(row))
    raw = b"".join(rows)

    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")
    with open(os.path.join(OUT, "textures", "panel.png"), "wb") as f:
        f.write(png)


if __name__ == "__main__":
    dart()
    raider()
    ring_station()
    panel_png()
    print("sample pack models written")
